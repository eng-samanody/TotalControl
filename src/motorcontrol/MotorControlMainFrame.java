    //this method receives a string and writes it to the connected port
    private void sendData(String dataToSend) 
    {
        SerialPort activePort = serialPort;
        try
        {
            // but wait.. we should never send anything unless the connection is opened
            // so we have to check if it is connected
            if(motorIsConnected && activePort != null)
            {
                activePort.writeBytes(dataToSend.getBytes());//Write data to port
            }
            else 
            {
                showError("Port is not connected");
            }
        }
        catch (SerialPortException  ex)
        {
            LOGGER.log(Level.WARNING, "Cannot write data to serial port", ex);
            showError("Cannot Write Data To Port");
        }
    }
    
       
    private void readPort()
    {
        final SerialPort activePort = serialPort;
        if (activePort == null) {
            throw new IllegalStateException("Serial port is not initialized");
        }
        try
        {
            int mask = SerialPort.MASK_RXCHAR + SerialPort.MASK_CTS + SerialPort.MASK_DSR;//Prepare mask
                activePort.setEventsMask(mask);//Set mask
                activePort.addEventListener(new  SerialPortEventListener() {
                @Override
                public void serialEvent(SerialPortEvent event) 
                {
                    if(event.isRXCHAR() && event.getEventValue() > 0) 
                    {
                        try 
                        {
                            final String receivedData = activePort.readString(event.getEventValue());
                            if (receivedData != null) {
                                SwingUtilities.invokeLater(new Runnable() {
                                    @Override
                                    public void run() {
                                        appendReceivedData(receivedData);
                                    }
                                });
                            }
                        }
                        catch (SerialPortException ex) 
                        {
                            LOGGER.log(Level.WARNING, "Error receiving data from serial port", ex);
                        }
                    }
                    else if(event.isCTS())
                    {//If CTS line has changed state
                        showLineStatus("CTS", event.getEventValue() == 1);
                    }
                    else if(event.isDSR())
                    {///If DSR line has changed state
                        showLineStatus("DSR", event.getEventValue() == 1);
                    }   
                }
            });//Add SerialPortEventListener
        }
        catch(Exception ex)
        {
            LOGGER.log(Level.WARNING, "Cannot initialize serial port listener", ex);
            throw new IllegalStateException("Cannot initialize serial port listener", ex);
        }
    }

    private void showLineStatus(final String lineName, final boolean on)
    {
        SwingUtilities.invokeLater(new Runnable() {
            @Override
            public void run() {
                JOptionPane.showMessageDialog(MotorControlMainFrame.this, lineName + (on ? " - ON" : " - OFF"),
                    "Serial line status", JOptionPane.INFORMATION_MESSAGE);
            }
        });
    }
    
    private void disconnect() throws HeadlessException {
        stopRepeatSending();
        stopPortMonitor();
        SerialPort activePort = serialPort;
        try
        {
            if(activePort != null)
            {
                activePort.closePort();//Close serial port
            }
        }
        catch (SerialPortException  ex)
        {
            LOGGER.log(Level.WARNING, "Cannot close serial port", ex);
            showError("Cannot close port");
        }
        finally
        {
            serialPort = null;
            motorIsConnected = false;
            motorIsRunning = false;
            enableDisable(true);
            disconnectButton.setEnabled(false);
            connectionStatusLabel.setIcon(new javax.swing.ImageIcon(getClass().getResource("/motorcontrol/img/disconnected.png")));
            connectionInfoLabel.setText("Disconnected");
        }
    }

    private void startPortMonitor()
    {
        stopPortMonitor();
        monitorRunning.set(true);
        checkPortThread = new Thread(this, "serial-port-monitor");
        checkPortThread.setDaemon(true);
        checkPortThread.start();
    }

    private void stopPortMonitor()
    {
        monitorRunning.set(false);
        if (checkPortThread != null) {
            checkPortThread.interrupt();
            checkPortThread = null;
        }
    }

    private void stopRepeatSending()
    {
        repeatSending.set(false);
        if (repeatSendThread != null) {
            repeatSendThread.interrupt();
            repeatSendThread = null;
        }
        if (repeatSendingCheckBox.isSelected()) {
            repeatSendingCheckBox.setSelected(false);
        }
    }
    
