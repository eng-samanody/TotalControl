    private void repeatSendingCheckBoxActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_repeatSendingCheckBoxActionPerformed

        if(repeatSendingCheckBox.isSelected())
        {
            if (motorIsConnected)
            {
                repeatSending.set(true);
                repeatSendThread = new Thread(new Runnable(){

                    @Override
                    public void run()
                    {
                        while(repeatSending.get())
                        {
                            try
                            {
                                sendData(getSendText());
                                int interval = Integer.parseInt(repeatIntervalSpinner.getValue().toString());
                                Thread.sleep(CommandProtocol.normalizeRepeatInterval(interval));
                            }
                            catch (InterruptedException ex)
                            {
                                Thread.currentThread().interrupt();
                                break;
                            }
                            catch (NumberFormatException ex)
                            {
                                LOGGER.log(Level.WARNING, "Invalid repeat interval", ex);
                                SwingUtilities.invokeLater(new Runnable() {
                                    @Override
                                    public void run() {
                                        stopRepeatSending();
                                        showError("Repeat interval must be a number");
                                    }
                                });
                                break;
                            }
                        }
                    }
                }, "serial-repeat-sender");
                repeatSendThread.setDaemon(true);
                repeatSendThread.start();
            }
            else
            {
                repeatSendingCheckBox.setSelected(false);
                showError("Port is not connected!!");
            }
        }
        else
        {
            stopRepeatSending();
        }
    }//GEN-LAST:event_repeatSendingCheckBoxActionPerformed

