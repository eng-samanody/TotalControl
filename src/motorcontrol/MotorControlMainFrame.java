    private void chooseLogFile()
    {
        JFileChooser chooser = new JFileChooser();
        chooser.setDialogTitle("Choose receive log file");
        int result = chooser.showSaveDialog(this);
        if (result == JFileChooser.APPROVE_OPTION) {
            logFile = chooser.getSelectedFile();
            jTextField3.setText(logFile.getAbsolutePath());
        }
    }

    private void setLoggingEnabled(boolean enabled)
    {
        if (enabled) {
            if (logFile == null) {
                chooseLogFile();
            }
            if (logFile == null) {
                startLogCheckBox.setSelected(false);
                return;
            }
            try {
                logWriter = new BufferedWriter(new FileWriter(logFile, true));
            } catch (IOException ex) {
                startLogCheckBox.setSelected(false);
                showError("Cannot open log file: " + ex.getMessage());
                LOGGER.log(Level.WARNING, "Cannot open receive log file", ex);
            }
        } else {
            closeLogWriter();
        }
    }

    private void closeLogWriter()
    {
        if (logWriter != null) {
            try {
                logWriter.close();
            } catch (IOException ex) {
                LOGGER.log(Level.WARNING, "Cannot close receive log file", ex);
            } finally {
                logWriter = null;
            }
        }
    }

    private void showError(final String message)
    {
        if (SwingUtilities.isEventDispatchThread()) {
            JOptionPane.showMessageDialog(MotorControlMainFrame.this, message, "Error", JOptionPane.ERROR_MESSAGE);
        } else {
            SwingUtilities.invokeLater(new Runnable() {
                @Override
                public void run() {
                    JOptionPane.showMessageDialog(MotorControlMainFrame.this, message, "Error", JOptionPane.ERROR_MESSAGE);
                }
            });
        }
    }

    private String getSendText()
    {
        if (SwingUtilities.isEventDispatchThread()) {
            return sendDataTextArea.getText();
        }
        final String[] value = new String[1];
        try {
            SwingUtilities.invokeAndWait(new Runnable() {
                @Override
                public void run() {
                    value[0] = sendDataTextArea.getText();
                }
            });
        } catch (Exception ex) {
            LOGGER.log(Level.WARNING, "Cannot read send text from UI", ex);
            return "";
        }
        return value[0] == null ? "" : value[0];
    }

    private void appendReceivedData(String data)
    {
        StringBuilder line = new StringBuilder();
        if (showDateCheckBox.isSelected() || showTimeCheckBox.isSelected()) {
            String pattern;
            if (showDateCheckBox.isSelected() && showTimeCheckBox.isSelected()) {
                pattern = "yyyy-MM-dd HH:mm:ss";
            } else if (showDateCheckBox.isSelected()) {
                pattern = "yyyy-MM-dd";
            } else {
                pattern = "HH:mm:ss";
            }
            line.append(new SimpleDateFormat(pattern).format(new Date())).append(" : ");
        }
        line.append(data);
        receivedDataTextArea.append(line.toString());
        writeLogLine(line.toString());
    }

    private void writeLogLine(String line)
    {
        if (logWriter == null) {
            return;
        }
        try {
            logWriter.write(line);
            logWriter.flush();
        } catch (IOException ex) {
            LOGGER.log(Level.WARNING, "Cannot write receive log", ex);
            closeLogWriter();
            startLogCheckBox.setSelected(false);
            showError("Cannot write to log file: " + ex.getMessage());
        }
    }


