    private void sendInteger(int integerToSend) 
    {
        SerialPort activePort = serialPort;
        if (!motorIsConnected || activePort == null) {
            showError("Port is not connected");
            return;
        }
        sendData(CommandProtocol.SPEED_PREFIX);
        try
        {            
            activePort.writeInt(integerToSend);
        }
        catch (SerialPortException  ex)
        {
             LOGGER.log(Level.WARNING, "Cannot write integer to serial port", ex);
             showError("Error Unable To Send Data!!");
        }
    }

