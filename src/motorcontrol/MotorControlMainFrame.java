    // check for the port existence
    private boolean checkAllPortNames()
    {
        availablePorts = SerialPortList.getPortNames();
        for (String availablePort : availablePorts) 
        {
            if (availablePort.equals(connectedPort)) 
            {
                //if the port matches the connected port so it exists
                return true;
            }
        }
        return false;
    }
    //override run method of the 
    @Override
    public void run() 
    {                                         
        while(monitorRunning.get())
        {            
            //check for the connected port existence and notify the user about port disonnection
            try
            {
                portExist = checkAllPortNames(); // check for the port existence
                if(!portExist && monitorRunning.compareAndSet(true, false)) // if the port doesn't exist
                {
                    SwingUtilities.invokeLater(new Runnable() {
                        @Override
                        public void run() {
                            handlePortDisconnected();
                        }
                    });
                    break;
                }
                Thread.sleep(PORT_MONITOR_INTERVAL_MS);
            }
            catch (InterruptedException ex)
            {
                Thread.currentThread().interrupt();
                break;
            }
            catch(Exception e)
            {
                LOGGER.log(Level.WARNING, "Serial port monitor failed", e);
                try {
                    Thread.sleep(PORT_MONITOR_INTERVAL_MS);
                } catch (InterruptedException ex) {
                    Thread.currentThread().interrupt();
                    break;
                }
            }
            //serialPort.setFlowControlMode(SerialPort.FLOWCONTROL_RTSCTS_IN | SerialPort.FLOWCONTROL_RTSCTS_OUT);            
            //serialPort.addEventListener(portReader, SerialPort.MASK_RXCHAR);            
        }
    }

    private void handlePortDisconnected()
    {
        int choice = JOptionPane.showConfirmDialog(MotorControlMainFrame.this,
            "Device disconnected, do you want to connect on other port?");
        if (choice == JOptionPane.YES_OPTION || choice == JOptionPane.CANCEL_OPTION)
        {
            currentPortsComboBox.removeAllItems();
            loadPortNames();

            if(motorIsRunning)
            {
                motorStopButton.doClick();
                motorIsRunning=false;
            }
            disconnect();
        }
        else if (choice == JOptionPane.NO_OPTION)
        {
            disconnect();
            System.exit(0);
        }
    }
